###
# Exports the configured units of one game version for the PC port's CMake build.
#
# `configure.py pc -v <VERSION>` resolves every object in config.libs exactly as the MWCC
# build does, translates the preprocessor-relevant flags (defines, include paths, prefix
# headers) and writes them to <build_dir>/<VERSION>/pc/units.json and units.cmake. Codegen
# flags are dropped. The CMake build includes units.cmake for the version it is configured
# for, so per-version source lists and library revisions always follow configure.py.
###

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from .project import Object, ProjectConfig, file_is_c_cpp, file_is_cpp


# Splits MWCC flags into defines, include dirs and prefix headers. Flags are given either as
# one string ("-i include") or as two list entries ("-i", "include").
def _parse_flags(flags: List[str]) -> Dict[str, List[str]]:
    defines: List[str] = []
    includes: List[str] = []
    includes_recursive: List[str] = []
    prefix_headers: List[str] = []
    pending: Optional[str] = None
    for flag in flags:
        if pending is not None:
            parts = [pending, flag]
            pending = None
        else:
            parts = flag.split(None, 1)
            if parts[0] in ("-i", "-I", "-ir", "-d", "-D", "-include", "-prefix") and len(parts) == 1:
                pending = parts[0]
                continue
        opt = parts[0]
        value = parts[1].strip().strip('"') if len(parts) > 1 else ""
        if opt in ("-i", "-I"):
            includes.append(value)
        elif opt == "-ir":
            includes_recursive.append(value)
        elif opt in ("-d", "-D"):
            defines.append(value)
        elif opt in ("-include", "-prefix"):
            prefix_headers.append(value)
        elif opt.startswith("-D") and len(opt) > 2:
            defines.append(opt[2:])
        elif opt.startswith("-I") and len(opt) > 2 and opt not in ("-I-", "-I+"):
            includes.append(opt[2:])
    return {
        "defines": defines,
        "includes": includes,
        "includes_recursive": includes_recursive,
        "prefix_headers": prefix_headers,
    }


def _expand_recursive(dirs: List[str]) -> List[str]:
    out: List[str] = []
    for d in dirs:
        root = Path(d)
        if not root.is_dir():
            continue
        out.append(root.as_posix())
        out.extend(sorted(p.as_posix() for p in root.rglob("*") if p.is_dir()))
    return out


def _dedupe(values: List[str]) -> List[str]:
    return list(dict.fromkeys(values))


def generate_pc_sources(config: ProjectConfig, version_num: int) -> Path:
    units: List[Dict[str, Any]] = []
    seen: Dict[str, str] = {}
    for lib in config.libs:
        for obj in lib["objects"]:
            assert isinstance(obj, Object)
            resolved = obj.resolve(config, lib)
            src_path = resolved.src_path
            if src_path is None or not file_is_c_cpp(src_path):
                continue
            key = src_path.as_posix()
            # Same source built twice (e.g. once per library flag set): keep the first
            if key in seen:
                continue
            seen[key] = lib["lib"]
            flags = [*(resolved.options["cflags"] or []), *(resolved.options["extra_cflags"] or [])]
            parsed = _parse_flags(flags)
            units.append(
                {
                    "lib": lib["lib"],
                    "name": resolved.name,
                    "source": key,
                    "exists": src_path.exists(),
                    "completed": bool(resolved.completed),
                    "lang": "cxx" if file_is_cpp(src_path) else "c",
                    "defines": _dedupe(parsed["defines"]),
                    "includes": _dedupe(
                        parsed["includes"] + _expand_recursive(parsed["includes_recursive"])
                    ),
                    "prefix_headers": _dedupe(parsed["prefix_headers"]),
                }
            )

    out_dir = config.out_path() / "pc"
    out_dir.mkdir(parents=True, exist_ok=True)
    data = {"version": config.version, "version_num": version_num, "units": units}
    with open(out_dir / "units.json", "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1)
    _write_cmake(out_dir / "units.cmake", data)
    return out_dir


def _cmake_list(values: List[str]) -> str:
    return ";".join(v.replace("\\", "/").replace(";", "\\;").replace('"', '\\"') for v in values)


# Writes one cf_unit() call per unit; the PC CMake project defines cf_unit() and decides
# which libraries and units it compiles.
def _write_cmake(path: Path, data: Dict[str, Any]) -> None:
    lines = [
        "# Generated by `configure.py pc`; do not edit.",
        f'set(CF_GEN_VERSION "{data["version"]}")',
        f'set(CF_GEN_VERSION_NUM {data["version_num"]})',
    ]
    for unit in data["units"]:
        if not unit["exists"]:
            continue
        lines.append(
            "cf_unit("
            f'LIB "{unit["lib"]}" '
            f'SOURCE "{unit["source"]}" '
            f'COMPLETED {"ON" if unit["completed"] else "OFF"} '
            f'DEFINES "{_cmake_list(unit["defines"])}" '
            f'INCLUDES "{_cmake_list(unit["includes"])}" '
            f'PREFIX_HEADERS "{_cmake_list(unit["prefix_headers"])}")'
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
