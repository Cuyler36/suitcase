# Generates the PC build's view of data the game takes straight from main.dol (used by
# src/cf/game/dol_data_loader.cpp).
#
# Usage: python tools/gen_pc_dol_data.py <symbols.txt> <out.cpp> NAME[:C] ...
#
# Each NAME is data copied from the disc's main.dol at startup. Emits a correctly sized, zeroed array
# (":C" gives it C linkage, for symbols the game declares extern "C").
# Names missing from this version's symbols.txt are skipped, so one list covers every version.
import re
import sys

symbols_txt, out_path = sys.argv[1], sys.argv[2]
blobs = []
for arg in sys.argv[3:]:
    name, _, link = arg.partition(":")
    blobs.append((name, link == "C"))

pattern = re.compile(r"^(\w+) = \.(\w+):0x([0-9A-Fa-f]+); // .*size:0x([0-9A-Fa-f]+)")
table = {}
with open(symbols_txt) as f:
    for line in f:
        m = pattern.match(line)
        if m:
            table[m.group(1)] = (m.group(2), int(m.group(3), 16), int(m.group(4), 16))

lines = [
    "// Generated by tools/gen_pc_dol_data.py from this version's symbols.txt; do not edit.",
    "// Used by cf::LoadDolData() (src/cf/game/dol_data_loader.cpp).",
    "#include <stddef.h>",
    "",
    "typedef unsigned char u8;",
    "typedef unsigned int u32;",
    "",
]
present_blobs = [(n, c) for n, c in blobs if n in table]
for name, c_linkage in present_blobs:
    section, addr, size = table[name]
    prefix = 'extern "C" ' if c_linkage else ""
    lines.append(f"{prefix}alignas(32) u8 {name}[0x{size:X}] = {{}}; // .{section}:0x{addr:08X}")

lines += ["", "namespace cf {", "", "struct DolBlob {", "    const char* name;", "    u8* dst;",
          "    u32 address;", "    u32 size;", "};", "", "extern const DolBlob kDolBlobs[] = {"]
for name, _ in present_blobs:
    _, addr, size = table[name]
    lines.append(f'    {{"{name}", {name}, 0x{addr:08X}, 0x{size:X}}},')
if not present_blobs:
    lines.append("    {nullptr, nullptr, 0, 0},")
lines += ["};", f"extern const size_t kDolBlobCount = {len(present_blobs)};", "", "} // namespace cf", ""]

with open(out_path, "w", newline="\n") as f:
    f.write("\n".join(lines))

missing = sorted(n for n, _ in blobs if n not in table)
print(f"{len(present_blobs)} DOL blobs"
      + (f"; not in this version: {' '.join(missing)}" if missing else ""))
